/* ------------------------------------------------------------------ */
/* Resolution helpers                                                  */
/* ------------------------------------------------------------------ */

const FALLBACK_ICON = 'QuestionMark';
const KEY_LOOKUP = Object.create(null);
for (const key of Object.keys(ICONS)) KEY_LOOKUP[key.toLowerCase()] = ICON_COPIES[key] || key;

const SUFFIX_RE = /(filled|regular|outlined|outline|light|solid|mirrored)$/;
const SIZE_RE = /\d+$/;

function lookupNormalized(norm) {
  if (!norm) return null;
  if (KEY_LOOKUP[norm]) return KEY_LOOKUP[norm];
  const target = ICON_ALIASES[norm];
  return target && ICONS[target] ? target : null;
}

/**
 * Resolve any icon name (modern Fluent string, classic `Icon.X` enum member, alias...)
 * to a key of ICONS, or null when unknown. Case-insensitive; strips a leading "Icon."
 * and trailing "Filled" / "Regular" / "Outline" (and size digits such as "24").
 */
export function resolveIconName(name) {
  if (name === null || name === undefined) return null;
  let s = String(name).trim().replace(/^["']+|["']+$/g, '');
  s = s.replace(/^ic_fluent_/i, '').replace(/^(icons?|fluent)\s*\./i, '');
  let norm = s.toLowerCase().replace(/[\s_.\-]+/g, '');
  for (let i = 0; i < 4 && norm; i++) {
    const hit = lookupNormalized(norm);
    if (hit) return hit;
    const next = norm.replace(SIZE_RE, '').replace(SUFFIX_RE, '').replace(SIZE_RE, '');
    if (next === norm) break;
    norm = next;
  }
  return null;
}

/** Primitives for a name; unknown names fall back to the QuestionMark placeholder. */
export function iconPrimitives(name) {
  return ICONS[resolveIconName(name) || FALLBACK_ICON];
}
